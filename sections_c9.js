window.switchC9Sub = function(targetId, btn) {
    document.querySelectorAll('.c9-sub-panel').forEach(p => p.style.display = 'none');
    document.querySelectorAll('.c9-pill-btn').forEach(b => {
        b.classList.remove('active');
        b.style.background = '#F8FAFC';
        b.style.color = '#334155';
        b.style.borderColor = '#CBD5E1';
    });
    const panel = document.getElementById(targetId);
    if (panel) panel.style.display = 'block';
    if (btn) {
        btn.classList.add('active');
        btn.style.background = '#1A1A1B';
        btn.style.color = '#FFFFFF';
        btn.style.borderColor = '#F39200';
    }
};

